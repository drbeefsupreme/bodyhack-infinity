import { POSE_SPECS } from '../spec';
import type { PoseId } from '../types';
import {
  ARMS,
  DIFFERENT_MAX,
  HIT_SCORE,
  POSE_IDS,
  clearlyDifferent,
  faultPasses,
  isGated,
  judge,
  type CaseResult,
  type GateRun,
  type Snapshot,
} from './criteria';

const SHORT: { readonly [P in PoseId]: string } = {
  relaxedFront: 'RF',
  quarterTurnLeftSide: 'QL',
  relaxedBack: 'RB',
  quarterTurnRightSide: 'QR',
  frontDoubleBiceps: 'FDB',
  frontLatSpread: 'FLS',
  sideChest: 'SC',
  backDoubleBiceps: 'BDB',
  backLatSpread: 'BLS',
  sideTriceps: 'ST',
  absAndThighs: 'AT',
  mostMuscular: 'MM',
};

/** Reference photos below this own-pose score are named under their table. */
const REFERENCE_FLOOR = 95;

const num = (score: number | null | undefined): string => (score === null || score === undefined ? '–' : score.toFixed(0));
const own = (row: CaseResult | undefined): number | null | undefined => row && row.scores[row.pose];

function table(head: readonly string[], rows: readonly (readonly string[])[]): string {
  const line = (cells: readonly string[]) => `| ${cells.join(' | ')} |`;
  return [line(head), line(head.map(() => '---')), ...rows.map(line)].join('\n');
}

/** Rows: rendered pose. Columns: called pose. Own scores in bold; a failing cell carries ✗. */
function matrix(run: GateRun): string {
  const rows = run.poses.map((row) => [
    `${SHORT[row.pose]}${isGated(row.pose) ? '' : ' (side)'}`,
    row.facing ?? '–',
    ...POSE_IDS.map((called) => {
      const score = row.scores[called];
      if (called === row.pose) return `**${num(score)}**${isGated(row.pose) && (score ?? 0) < HIT_SCORE ? ' ✗' : ''}`;
      const failing = isGated(row.pose) && score !== null && score >= DIFFERENT_MAX && clearlyDifferent(row.pose, called);
      return `${num(score)}${failing ? ' ✗' : ''}`;
    }),
  ]);
  return table(['rendered \\ called', 'facing', ...POSE_IDS.map((id) => SHORT[id])], rows);
}

function backend(run: GateRun): string {
  const { renderer, software, delegate } = run.backend;
  return `${software ? 'SwiftShader (software fallback)' : 'GPU'}: \`${renderer}\`; MediaPipe delegate ${delegate}`;
}

export function renderReport(final: GateRun, snapshots: readonly Snapshot[]): string {
  const { failures, lookAlikes } = judge(final);
  const shorts = (keep: (id: PoseId) => boolean) => POSE_IDS.filter(keep).map((id) => SHORT[id]).join(', ');
  const labels = snapshots.map((s) => s.label);
  const ownRows = final.poses.map((row) => {
    const score = own(row);
    return [
      POSE_SPECS[row.pose][0].name,
      ...snapshots.map((s) => num(own(s.run.poses.find((b) => b.id === row.id)))),
      `**${num(score)}**`,
      `${row.detected}/${final.frames}`,
      row.facing ?? '–',
      row.topCue ?? '–',
      isGated(row.pose) ? ((score ?? 0) >= HIT_SCORE ? 'pass' : 'FAIL') : 'informative',
    ];
  });
  const faultRows = final.faults.map((f) => [
    f.label,
    `"${f.expectedCue}"`,
    ...snapshots.map((s) => {
      const before = s.run.faults.find((b) => b.id === f.id);
      return before ? `${num(own(before))}, "${before.topCue ?? '–'}"` : '–';
    }),
    `**${num(own(f))}**, "${f.topCue ?? '–'}"`,
    faultPasses(f) ? 'pass' : 'FAIL',
  ]);
  const refRows = final.references.map((ref) => [
    ref.id,
    SHORT[ref.pose],
    ...snapshots.map((s) => {
      const before = s.run.references.find((b) => b.id === ref.id);
      return before?.score === null || before === undefined ? '–' : before.score.toFixed(1);
    }),
    ref.score === null ? '–' : ref.score.toFixed(1),
  ]);
  const lowRefs = final.references.filter((r) => r.score !== null && r.score < REFERENCE_FLOOR);
  const unscoredRefs = final.references.filter((r) => r.score === null);

  const out = [
    '# Tracking gate report',
    '',
    'Generated by `npm run gate` (`scripts/gate.ts`, harness `gate.html` and `src/posing/gate/`). Do not edit by hand.',
    '',
    `Run ${final.at}. Backend: ${backend(final)}. Frames ${final.size[0]}x${final.size[1]}, ${final.frames} per pose, median score. ` +
      `Calibration from the relaxed-front render: ${final.calibrated ? 'yes' : 'no'}.`,
    '',
    `**Result: ${failures.length === 0 ? 'PASS' : `FAIL (${failures.length})`}**`,
    ...failures.map((f) => `- ${f}`),
    '',
    '## Pass criteria',
    '',
    `1. Own pose: every pose scored from the front or back (${shorts(isGated)}) scores at least ${HIT_SCORE} for itself.`,
    `2. Clearly different poses score below ${DIFFERENT_MAX} ("–", no score, counts as below). Two poses are clearly different ` +
      `when they share no facing, or when one has the arms overhead (${shorts((id) => ARMS[id] === 'overhead')}) and the other has them down.`,
    '3. Pairs with the same facing and arm class are 2D look-alikes. Their cross scores are listed below and do not fail ' +
      'the gate; for example front lat spread and most muscular with the hands on the hips look the same to a front camera.',
    `4. Side poses (${shorts((id) => !isGated(id))}) are informative only: a front camera sees side poses poorly.`,
    `5. Each fault render gives its expected cue as the top correction and scores below ${HIT_SCORE}.`,
    '',
    '## How a case runs',
    '',
    'The figure is rendered with the app\'s Viewer from the judges\' view (front camera, full body, plain wall) and each ' +
      'canvas frame goes through the live pipeline: `createTracker` (MediaPipe Pose Landmarker, VIDEO mode), ' +
      '`LandmarkSmoother`, `measure` (calibrated on the relaxed-front render), `classifyFacing` through the facing ' +
      'hysteresis (`filterFacing`) and `scoreCall` for all 12 calls.',
    '',
    'Each case starts with empty frames, so MediaPipe loses the previous case, then shows the relaxed stance of the ' +
      'call\'s facing, as between calls at prejudging, then the pose. Without the empty frames, VIDEO mode carried the ' +
      'previous case\'s tracking region into the next case, and a score changed when an earlier pose changed (abs and ' +
      'thighs moved from 88 to 84.8 after a side triceps edit). Without the relaxed lead-in, a fresh detection of abs and ' +
      'thighs misplaced the trunk (shoulders at the head, hips at the knees) and scored 35.',
    '',
    '## Changes since the baseline',
    '',
    ...snapshots.map((s, i) => `${i + 1}. **${s.label}** (${judge(s.run).failures.length} failures): ${s.note}`),
    `${snapshots.length + 1}. **final** (${failures.length} failures): this run.`,
    '',
    '## Own-pose scores',
    '',
    table(['pose', ...labels, 'final', 'detected', 'facing', 'top cue (final)', 'verdict'], ownRows),
    '',
    '## Final matrix',
    '',
    'Rows are the rendered pose, columns the called pose. Bold is the own score; ✗ marks a failing cell.',
    '',
    matrix(final),
    '',
    '## 2D look-alikes (not failures)',
    '',
    lookAlikes.length === 0
      ? `No same-facing, same-arm-class pair scored ${DIFFERENT_MAX} or more.`
      : table(
          ['rendered', 'called', 'score'],
          lookAlikes.map((l) => [SHORT[l.rendered], SHORT[l.called], l.score.toFixed(0)]),
        ),
    '',
    '## Fault renders',
    '',
    'Score and top cue of the broken pose\'s own call.',
    '',
    table(['fault', 'expected top cue', ...labels, 'final', 'verdict'], faultRows),
    '',
    '## Reference photos',
    '',
    'Own-pose score of the 26 reference photos (`src/posing/fixtures`) under the scoring of each run.',
    '',
    table(['photo', 'pose', ...labels, 'final'], refRows),
    '',
    `Below ${REFERENCE_FLOOR} in this run: ${lowRefs.map((r) => `${r.id} ${r.score?.toFixed(1)}`).join(', ') || 'none'}. ` +
      `No score: ${unscoredRefs.map((r) => r.id).join(', ') || 'none'}.`,
    '',
    '## Contact sheet',
    '',
    'The frames that went into MediaPipe, cropped, with the smoothed landmarks drawn on top.',
    '',
    '![Figure poses as the tracker saw them](img/gate-poses.webp)',
    '',
  ];
  for (const s of snapshots) {
    out.push(`## Matrix: ${s.label}`, '', `Run ${s.run.at}. Backend: ${backend(s.run)}. ${s.note}`, '', matrix(s.run), '');
  }
  return out.join('\n');
}
